using System.Globalization;
using System.Text;
using System.Text.Encodings.Web;
using System.Text.Json;
using SportsPlatform.Modules.Identity.Domain.Roles;

namespace SportsPlatform.Host.Catalogues;

/// <summary>
/// The system roles and the actions each grants (S03 D9), exported by the CLI to <c>docs/generated/roles.md</c> and
/// <c>contracts/roles.json</c>, so the catalogue shows who can do what.
/// </summary>
public static class RoleCatalogueExport
{
    public static string ToMarkdown(RoleCatalogue catalogue)
    {
        ArgumentNullException.ThrowIfNull(catalogue);

        var markdown = new StringBuilder()
            .Append("# Roles\n\n")
            .Append("Generated by `dotnet run --project backend/tools/SportsPlatform.Cli -- export-catalogues`; do not edit.\n")
            .Append("Defined in code in Identity's `IdentityRoles` (docs/architecture/authorization.md). Assignments store the\n")
            .Append("role code; the actions are those in `actions.md`. Account actions need no role.\n\n")
            .Append("| Role | Scope | Assignable at | Actions | Description |\n")
            .Append("|---|---|---|---|---|\n");
        foreach (var role in catalogue.Roles)
        {
            var assignableAt = role.AssignableAt.Count == 0 ? "—" : string.Join(", ", role.AssignableAt.Select(ActionCatalogue.ToConstant));
            var actions = role.Actions.Count == 0 ? "—" : string.Join(", ", role.Actions.Select(code => $"`{code}`"));
            markdown.Append(CultureInfo.InvariantCulture,
                $"| `{role.Code}` | {ActionCatalogue.ToConstant(role.Scope)} | {assignableAt} | {actions} | {role.Description.Replace("|", "\\|", StringComparison.Ordinal)} |\n");
        }

        return markdown.ToString();
    }

    public static string ToJson(RoleCatalogue catalogue)
    {
        ArgumentNullException.ThrowIfNull(catalogue);

        var options = new JsonWriterOptions { Indented = true, NewLine = "\n", Encoder = JavaScriptEncoder.UnsafeRelaxedJsonEscaping };
        using var stream = new MemoryStream();
        using (var writer = new Utf8JsonWriter(stream, options))
        {
            writer.WriteStartObject();
            writer.WriteStartArray("roles");
            foreach (var role in catalogue.Roles)
            {
                writer.WriteStartObject();
                writer.WriteString("code", role.Code);
                writer.WriteString("scope", ActionCatalogue.ToConstant(role.Scope));
                writer.WriteString("description", role.Description);
                writer.WriteStartArray("assignableAt");
                foreach (var scope in role.AssignableAt)
                {
                    writer.WriteStringValue(ActionCatalogue.ToConstant(scope));
                }

                writer.WriteEndArray();
                writer.WriteStartArray("actions");
                foreach (var code in role.Actions)
                {
                    writer.WriteStringValue(code);
                }

                writer.WriteEndArray();
                writer.WriteEndObject();
            }

            writer.WriteEndArray();
            writer.WriteEndObject();
        }

        return Encoding.UTF8.GetString(stream.ToArray()) + "\n";
    }
}
