using System.Globalization;
using System.Reflection;
using System.Text;
using System.Text.Encodings.Web;
using System.Text.Json;
using SportsPlatform.BuildingBlocks.Actions;
using SportsPlatform.BuildingBlocks.Modules;

namespace SportsPlatform.Host.Catalogues;

public sealed record ActionCatalogueEntry(ActionDefinition Action, string Module);

/// <summary>
/// Every declared action: the <c>public static readonly ActionDefinition</c> fields of static <c>*Actions</c> classes in
/// each module assembly. Exported by the CLI to <c>docs/generated/actions.md</c> and <c>contracts/actions.json</c>.
/// </summary>
public static class ActionCatalogue
{
    public static IReadOnlyList<ActionCatalogueEntry> Build(IEnumerable<IModule> modules)
    {
        ArgumentNullException.ThrowIfNull(modules);

        var entries = modules
            .Select(module => (module.Name, Assembly: module.GetType().Assembly))
            .DistinctBy(source => source.Assembly)
            .SelectMany(source => DeclaringTypes(source.Assembly)
                .SelectMany(type => type.GetFields(BindingFlags.Public | BindingFlags.Static))
                .Where(field => field.FieldType == typeof(ActionDefinition) && field.IsInitOnly)
                .Select(field => new ActionCatalogueEntry((ActionDefinition)field.GetValue(null)!, source.Name)))
            .OrderBy(entry => entry.Action.Code.Value, StringComparer.Ordinal)
            .ToList();

        var duplicates = entries.GroupBy(entry => entry.Action.Code).Where(group => group.Count() > 1).Select(group => group.Key).ToList();
        if (duplicates.Count > 0)
        {
            throw new InvalidOperationException($"Action codes declared more than once: {string.Join(", ", duplicates)}.");
        }

        return entries;
    }

    /// <summary>Static classes whose name ends in <c>Actions</c>.</summary>
    public static IEnumerable<Type> DeclaringTypes(Assembly assembly)
    {
        ArgumentNullException.ThrowIfNull(assembly);
        return assembly.GetTypes().Where(type =>
            type is { IsClass: true, IsAbstract: true, IsSealed: true } && type.Name.EndsWith("Actions", StringComparison.Ordinal));
    }

    public static string ToMarkdown(IReadOnlyList<ActionCatalogueEntry> entries)
    {
        ArgumentNullException.ThrowIfNull(entries);

        var markdown = new StringBuilder()
            .Append("# Actions\n\n")
            .Append("Generated by `dotnet run --project backend/tools/SportsPlatform.Cli -- export-catalogues`; do not edit.\n")
            .Append("Declared in each module's `*Actions` class (docs/architecture/authorization.md). Every state-changing or\n")
            .Append("admin endpoint requires one of these; the code is stable and is what roles grant.\n\n")
            .Append("| Code | Module | Scope | Scopable by | Audit | Entitlement | Idempotent | Since | Description |\n")
            .Append("|---|---|---|---|---|---|---|---|---|\n");
        foreach (var (action, module) in entries)
        {
            var scopableBy = action.ScopableBy.Count == 0 ? "—" : string.Join(", ", action.ScopableBy.Select(ToConstant));
            var entitlement = action.Entitlement is null ? "—" : $"`{action.Entitlement}`";
            markdown.Append(CultureInfo.InvariantCulture,
                $"| `{action.Code}` | {module} | {ToConstant(action.Scope)} | {scopableBy} | {ToConstant(action.Audit)} | {entitlement} | {(action.Idempotent ? "yes" : "no")} | {action.Since} | {action.Description.Replace("|", "\\|", StringComparison.Ordinal)} |\n");
        }

        return markdown.ToString();
    }

    public static string ToJson(IReadOnlyList<ActionCatalogueEntry> entries)
    {
        ArgumentNullException.ThrowIfNull(entries);

        var options = new JsonWriterOptions { Indented = true, NewLine = "\n", Encoder = JavaScriptEncoder.UnsafeRelaxedJsonEscaping };
        using var stream = new MemoryStream();
        using (var writer = new Utf8JsonWriter(stream, options))
        {
            writer.WriteStartObject();
            writer.WriteStartArray("actions");
            foreach (var (action, module) in entries)
            {
                writer.WriteStartObject();
                writer.WriteString("code", action.Code.Value);
                writer.WriteString("module", module);
                writer.WriteString("description", action.Description);
                writer.WriteString("scope", ToConstant(action.Scope));
                writer.WriteStartArray("scopableBy");
                foreach (var scope in action.ScopableBy)
                {
                    writer.WriteStringValue(ToConstant(scope));
                }

                writer.WriteEndArray();
                writer.WriteString("audit", ToConstant(action.Audit));
                writer.WriteString("entitlement", action.Entitlement);
                writer.WriteBoolean("idempotent", action.Idempotent);
                writer.WriteString("since", action.Since);
                writer.WriteEndObject();
            }

            writer.WriteEndArray();
            writer.WriteEndObject();
        }

        return Encoding.UTF8.GetString(stream.ToArray()) + "\n";
    }

    /// <summary><c>RequiredWithReason</c> → <c>REQUIRED_WITH_REASON</c>, as authorization.md writes the values.</summary>
    public static string ToConstant<TEnum>(TEnum value)
        where TEnum : struct, Enum
    {
        var name = value.ToString();
        var constant = new StringBuilder(name.Length + 4);
        for (var i = 0; i < name.Length; i++)
        {
            if (i > 0 && char.IsUpper(name[i]))
            {
                constant.Append('_');
            }

            constant.Append(char.ToUpperInvariant(name[i]));
        }

        return constant.ToString();
    }
}
