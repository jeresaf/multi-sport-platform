using System.Globalization;
using System.Reflection;
using System.Text;
using System.Text.Encodings.Web;
using System.Text.Json;
using SportsPlatform.BuildingBlocks.Entitlements;
using SportsPlatform.BuildingBlocks.Modules;
using SportsPlatform.Modules.Tenancy.Domain.Plans;

namespace SportsPlatform.Host.Catalogues;

public sealed record EntitlementCatalogueEntry(EntitlementDefinition Entitlement, string Module);

/// <summary>
/// Every declared entitlement: the <c>public static readonly EntitlementDefinition</c> fields of static
/// <c>*Entitlements</c> classes in each module assembly (S04 D1). Exported by the CLI, with each plan's value and the
/// actions that name it, to <c>docs/generated/entitlements.md</c> and <c>contracts/entitlements.json</c>.
/// </summary>
public static class EntitlementCatalogue
{
    public static IReadOnlyList<EntitlementCatalogueEntry> Build(IEnumerable<IModule> modules)
    {
        ArgumentNullException.ThrowIfNull(modules);

        var catalogue = modules
            .SelectMany(module => DeclaringTypes(module.GetType().Assembly)
                .SelectMany(type => type.GetFields(BindingFlags.Public | BindingFlags.Static))
                .Where(field => field.FieldType == typeof(EntitlementDefinition) && field.IsInitOnly)
                .Select(field => new EntitlementCatalogueEntry((EntitlementDefinition)field.GetValue(null)!, module.Name)))
            .OrderBy(entry => entry.Entitlement.Code, StringComparer.Ordinal)
            .ToList();

        var duplicates = catalogue.GroupBy(entry => entry.Entitlement.Code, StringComparer.Ordinal)
            .Where(group => group.Count() > 1)
            .Select(group => group.Key)
            .ToList();
        if (duplicates.Count > 0)
        {
            throw new InvalidOperationException($"Entitlement codes declared more than once: {string.Join(", ", duplicates)}.");
        }

        return catalogue;
    }

    /// <summary>Static classes whose name ends in <c>Entitlements</c>.</summary>
    public static IEnumerable<Type> DeclaringTypes(Assembly assembly)
    {
        ArgumentNullException.ThrowIfNull(assembly);
        return assembly.GetTypes().Where(type =>
            type is { IsClass: true, IsAbstract: true, IsSealed: true } && type.Name.EndsWith("Entitlements", StringComparison.Ordinal));
    }

    public static string ToMarkdown(
        IReadOnlyList<EntitlementCatalogueEntry> entries, IReadOnlyList<PlanDefinition> plans, IReadOnlyList<ActionCatalogueEntry> actions)
    {
        ArgumentNullException.ThrowIfNull(entries);
        ArgumentNullException.ThrowIfNull(plans);
        ArgumentNullException.ThrowIfNull(actions);

        var markdown = new StringBuilder()
            .Append("# Entitlements\n\n")
            .Append("Generated by `dotnet run --project backend/tools/SportsPlatform.Cli -- export-catalogues`; do not edit.\n")
            .Append("Declared in Tenancy's `TenancyEntitlements`, valued per plan in `TenancyPlans` (docs/architecture/authorization.md,\n")
            .Append("\"Entitlements\"). A tenant with no subscription period gets the default.\n\n")
            .Append("| Code | Name | Type | Unit | Levels | Default |");
        foreach (var plan in plans)
        {
            markdown.Append(CultureInfo.InvariantCulture, $" {plan.Code} |");
        }

        markdown.Append(" Enforced by | Actions | Since | Description |\n|---|---|---|---|---|---|");
        markdown.Append(string.Concat(plans.Select(_ => "---|")));
        markdown.Append("---|---|---|---|\n");

        foreach (var (entitlement, _) in entries)
        {
            var levels = entitlement.Levels.Count == 0 ? "—" : string.Join(" < ", entitlement.Levels.Select(level => $"`{level}`"));
            var naming = ActionsNaming(entitlement, actions);
            markdown.Append(CultureInfo.InvariantCulture,
                $"| `{entitlement.Code}` | {Escape(entitlement.Name)} | {ActionCatalogue.ToConstant(entitlement.Type)} | {entitlement.Unit ?? "—"} | {levels} | {entitlement.Default} |");
            foreach (var plan in plans)
            {
                markdown.Append(CultureInfo.InvariantCulture, $" {ValueOn(plan, entitlement)?.ToString() ?? "—"} |");
            }

            markdown.Append(CultureInfo.InvariantCulture,
                $" {Escape(entitlement.EnforcedBy)} | {(naming.Count == 0 ? "—" : string.Join(", ", naming.Select(code => $"`{code}`")))} | {entitlement.Since} | {Escape(entitlement.Description)} |\n");
        }

        return markdown.ToString();
    }

    public static string ToJson(
        IReadOnlyList<EntitlementCatalogueEntry> entries, IReadOnlyList<PlanDefinition> plans, IReadOnlyList<ActionCatalogueEntry> actions)
    {
        ArgumentNullException.ThrowIfNull(entries);
        ArgumentNullException.ThrowIfNull(plans);
        ArgumentNullException.ThrowIfNull(actions);

        var options = new JsonWriterOptions { Indented = true, NewLine = "\n", Encoder = JavaScriptEncoder.UnsafeRelaxedJsonEscaping };
        using var stream = new MemoryStream();
        using (var writer = new Utf8JsonWriter(stream, options))
        {
            writer.WriteStartObject();
            writer.WriteStartArray("plans");
            foreach (var plan in plans)
            {
                writer.WriteStartObject();
                writer.WriteString("code", plan.Code);
                writer.WriteString("name", plan.Name);
                writer.WriteNumber("rank", plan.Rank);
                writer.WriteEndObject();
            }

            writer.WriteEndArray();
            writer.WriteStartArray("entitlements");
            foreach (var (entitlement, module) in entries)
            {
                writer.WriteStartObject();
                writer.WriteString("code", entitlement.Code);
                writer.WriteString("module", module);
                writer.WriteString("name", entitlement.Name);
                writer.WriteString("description", entitlement.Description);
                writer.WriteString("type", ActionCatalogue.ToConstant(entitlement.Type));
                writer.WriteString("unit", entitlement.Unit);
                writer.WriteStartArray("levels");
                foreach (var level in entitlement.Levels)
                {
                    writer.WriteStringValue(level);
                }

                writer.WriteEndArray();
                writer.WritePropertyName("default");
                WriteValue(writer, entitlement.Default);
                writer.WriteStartObject("plans");
                foreach (var plan in plans)
                {
                    writer.WritePropertyName(plan.Code);
                    if (ValueOn(plan, entitlement) is { } value)
                    {
                        WriteValue(writer, value);
                    }
                    else
                    {
                        writer.WriteNullValue();
                    }
                }

                writer.WriteEndObject();
                writer.WriteString("enforcedBy", entitlement.EnforcedBy);
                writer.WriteStartArray("actions");
                foreach (var code in ActionsNaming(entitlement, actions))
                {
                    writer.WriteStringValue(code);
                }

                writer.WriteEndArray();
                writer.WriteString("since", entitlement.Since);
                writer.WriteEndObject();
            }

            writer.WriteEndArray();
            writer.WriteEndObject();
        }

        return Encoding.UTF8.GetString(stream.ToArray()) + "\n";
    }

    // { "enabled": true } | { "limit": 120 } (null = unlimited) | { "level": "BASIC" } (null = none): typed, never a bare scalar.
    private static void WriteValue(Utf8JsonWriter writer, EntitlementValue value)
    {
        writer.WriteStartObject();
        switch (value.Type)
        {
            case EntitlementType.Boolean:
                writer.WriteBoolean("enabled", value.Enabled);
                break;
            case EntitlementType.Quota:
                if (value.Limit is { } limit)
                {
                    writer.WriteNumber("limit", limit);
                }
                else
                {
                    writer.WriteNull("limit");
                }

                break;
            case EntitlementType.Level:
                writer.WriteString("level", value.LevelCode);
                break;
            default:
                throw new InvalidOperationException($"Unknown entitlement type {value.Type}.");
        }

        writer.WriteEndObject();
    }

    private static EntitlementValue? ValueOn(PlanDefinition plan, EntitlementDefinition entitlement) =>
        plan.Values.GetValueOrDefault(entitlement.Code);

    private static List<string> ActionsNaming(EntitlementDefinition entitlement, IReadOnlyList<ActionCatalogueEntry> actions) =>
        [.. actions.Where(entry => entry.Action.Entitlement == entitlement.Code).Select(entry => entry.Action.Code.Value)];

    private static string Escape(string text) => text.Replace("|", "\\|", StringComparison.Ordinal);
}
