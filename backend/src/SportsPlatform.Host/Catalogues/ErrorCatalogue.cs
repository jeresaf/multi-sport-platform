using System.Globalization;
using System.Reflection;
using System.Text;
using System.Text.Json;
using SportsPlatform.BuildingBlocks.Api;
using SportsPlatform.BuildingBlocks.Modules;
using SportsPlatform.BuildingBlocks.Results;

namespace SportsPlatform.Host.Catalogues;

public sealed record ErrorCatalogueEntry(string Code, int Status, string Message, string Owner);

/// <summary>
/// Every declared error: the <c>public static readonly Error</c> fields of static <c>*Errors</c> classes in
/// BuildingBlocks and each module assembly. Exported by the CLI to <c>docs/generated/errors.md</c> and
/// <c>contracts/errors.json</c>.
/// </summary>
public static class ErrorCatalogue
{
    public const string BuildingBlocksOwner = "BuildingBlocks";

    public static IReadOnlyList<ErrorCatalogueEntry> Build(IEnumerable<IModule> modules)
    {
        ArgumentNullException.ThrowIfNull(modules);

        var sources = new List<(string Owner, Assembly Assembly)> { (BuildingBlocksOwner, typeof(Error).Assembly) };
        sources.AddRange(modules.Select(module => (module.Name, module.GetType().Assembly)));

        var entries = sources
            .DistinctBy(source => source.Assembly)
            .SelectMany(source => DeclaringTypes(source.Assembly)
                .SelectMany(type => type.GetFields(BindingFlags.Public | BindingFlags.Static))
                .Where(field => field.FieldType == typeof(Error) && field.IsInitOnly)
                .Select(field => (Error)field.GetValue(null)!)
                .Select(error => new ErrorCatalogueEntry(error.Code, error.Kind.ToStatusCode(), error.Message, source.Owner)))
            .OrderBy(entry => entry.Code, StringComparer.Ordinal)
            .ToList();

        var duplicates = entries.GroupBy(entry => entry.Code).Where(group => group.Count() > 1).Select(group => group.Key).ToList();
        if (duplicates.Count > 0)
        {
            throw new InvalidOperationException($"Error codes declared more than once: {string.Join(", ", duplicates)}.");
        }

        return entries;
    }

    /// <summary>Static classes whose name ends in <c>Errors</c>.</summary>
    public static IEnumerable<Type> DeclaringTypes(Assembly assembly)
    {
        ArgumentNullException.ThrowIfNull(assembly);
        return assembly.GetTypes().Where(type =>
            type is { IsClass: true, IsAbstract: true, IsSealed: true } && type.Name.EndsWith("Errors", StringComparison.Ordinal));
    }

    public static string ToMarkdown(IReadOnlyList<ErrorCatalogueEntry> entries)
    {
        ArgumentNullException.ThrowIfNull(entries);

        var markdown = new StringBuilder()
            .Append("# Error codes\n\n")
            .Append("Generated by `dotnet run --project backend/tools/SportsPlatform.Cli -- export-catalogues`; do not edit.\n")
            .Append("Declared in each module's `*Errors` class (docs/architecture/api-conventions.md). The code is stable;\n")
            .Append("the message is the default title and may change.\n\n")
            .Append("| Code | HTTP | Default message | Owner |\n")
            .Append("|---|---|---|---|\n");
        foreach (var entry in entries)
        {
            markdown.Append(CultureInfo.InvariantCulture, $"| `{entry.Code}` | {entry.Status} | {entry.Message.Replace("|", "\\|", StringComparison.Ordinal)} | {entry.Owner} |\n");
        }

        return markdown.ToString();
    }

    public static string ToJson(IReadOnlyList<ErrorCatalogueEntry> entries)
    {
        ArgumentNullException.ThrowIfNull(entries);

        using var stream = new MemoryStream();
        using (var writer = new Utf8JsonWriter(stream, new JsonWriterOptions { Indented = true, NewLine = "\n" }))
        {
            writer.WriteStartObject();
            writer.WriteStartArray("errors");
            foreach (var entry in entries)
            {
                writer.WriteStartObject();
                writer.WriteString("code", entry.Code);
                writer.WriteNumber("status", entry.Status);
                writer.WriteString("message", entry.Message);
                writer.WriteString("owner", entry.Owner);
                writer.WriteEndObject();
            }

            writer.WriteEndArray();
            writer.WriteEndObject();
        }

        return Encoding.UTF8.GetString(stream.ToArray()) + "\n";
    }
}
